"""Reproduce the pinned browser assets without npm or a frontend build step.

Run with uv run scripts/vendor_browser_dependencies.py [--check]. Network access
is required only for vendoring/verification, never for serving the Finchvox UI.
The upstream distribution payloads are retained byte-for-byte after a banner.
"""

import argparse
import base64
import hashlib
import io
import json
import tarfile
from pathlib import Path
from urllib.request import urlopen

ROOT = Path(__file__).resolve().parents[1]
LIB_DIR = ROOT / "ui" / "lib"
MAX_DOWNLOAD_BYTES = 16 * 1024 * 1024


def download(url):
    if not url.startswith("https://"):
        raise ValueError("Vendor sources must use HTTPS")
    with urlopen(url, timeout=30) as response:
        data = response.read(MAX_DOWNLOAD_BYTES + 1)
    if len(data) > MAX_DOWNLOAD_BYTES:
        raise ValueError(f"Vendor source exceeds size limit: {url}")
    return data


def read_member(archive, name):
    member = archive.getmember(name)
    if not member.isfile() or member.size > MAX_DOWNLOAD_BYTES:
        raise ValueError(f"Invalid vendor archive member: {name}")
    # Read exactly the selected member; never extract an archive to disk.
    with archive.extractfile(member) as source:
        return source.read()


def banner(package):
    return (
        f"/*! Vendored {package['name']} {package['version']}; "
        f"{package['license']}. See THIRD_PARTY_LICENSES.txt. "
        f"Source: {package['tarball']} */\n"
    ).encode()


def package_contents(package):
    data = download(package["tarball"])
    integrity = "sha512-" + base64.b64encode(hashlib.sha512(data).digest()).decode()
    if integrity != package["integrity"]:
        raise ValueError(f"Archive integrity mismatch: {package['name']}")
    with tarfile.open(fileobj=io.BytesIO(data), mode="r:gz") as archive:
        payload = read_member(archive, package["member"])
        if hashlib.sha256(payload).hexdigest() != package["payload_sha256"]:
            raise ValueError(f"Asset digest mismatch: {package['name']}")
        licenses = {
            item.name: read_member(archive, item.name)
            for item in archive.getmembers()
            if item.name in ("package/LICENSE", "package/LICENSE.md")
        }
    return banner(package) + payload, licenses


def notice_text(notice, licenses):
    if "package" in notice:
        return licenses[notice["package"]][notice["member"]].decode()
    data = download(notice["url"])
    if hashlib.sha256(data).hexdigest() != notice["sha256"]:
        raise ValueError(f"License digest mismatch: {notice['title']}")
    return data.decode()


def render_notices(manifest, licenses):
    lines = [
        "Vendored browser libraries",
        "=========================",
        "",
        "Generated by scripts/vendor_browser_dependencies.py.",
        "Sources and integrity hashes: vendor-manifest.json.",
        "",
    ]
    for package in manifest["packages"]:
        lines.extend([
            f"{package['file']}: {package['name']} {package['version']} ({package['license']})",
            package["tarball"],
            "",
        ])
    for notice in manifest["notices"]:
        text = notice_text(notice, licenses).replace("\r\n", "\n").strip()
        lines.extend([notice["title"], "-" * len(notice["title"]), "", text, ""])
    return "\n".join(lines).encode()


def expected_files(manifest):
    files, licenses = {}, {}
    for package in manifest["packages"]:
        files[package["file"]], licenses[package["name"]] = package_contents(package)
    files["THIRD_PARTY_LICENSES.txt"] = render_notices(manifest, licenses)
    return files


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Verify without writing files")
    args = parser.parse_args()
    manifest = json.loads((LIB_DIR / "vendor-manifest.json").read_text(encoding="utf-8"))
    # Validate every downloaded payload and license before replacing any asset.
    for name, content in expected_files(manifest).items():
        path = LIB_DIR / name
        if args.check:
            if not path.exists() or path.read_bytes() != content:
                raise SystemExit(f"Vendored file differs from pinned source: {name}")
        else:
            path.write_bytes(content)
        print(f"{'Verified' if args.check else 'Vendored'} {name}")


if __name__ == "__main__":
    main()
